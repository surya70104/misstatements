// ---- the export ----

test('before an evaluation run the paper cannot be exported, and says why', async () => {
  await open(noRun)
  const panelExport = panel('Export to the binder')
  expect(panelExport).toHaveTextContent('Latest export:None recorded')
  expect(exportButton()).toBeDisabled()
  const reasons = within(panelExport).getByRole('list', {
    name: 'Why the paper cannot be exported',
  })
  expect(reasons).toHaveTextContent(noRun.exportable.reasons[0] ?? 'missing')
  expect(reasons).toHaveTextContent('record a run first')
  expect(panelExport).toHaveTextContent(`Content hash now: ${noRun.content_hash}`)
  expect(noRun.content_hash).toMatch(/^[0-9a-f]{64}$/)
  expect(panelExport).toHaveTextContent('Registered papersNone yet.')
})

test('exporting registers the paper, shows the hash, and reads the paper again', async () => {
  await open(ready, [], {
    [paperPath(ready)]: inTurn(ready, current),
    [exportsPath(ready)]: inTurn([], registrations),
    [exportPath(ready)]: answered(201, exported),
  })
  expect(exportButton()).toBeEnabled()
  fireEvent.click(exportButton())
  expect(await screen.findByText('Registered as paper 1, on evaluation run 1.')).toBeInTheDocument()
  expect(sent()).toEqual([
    { request: exportPath(ready), body: {}, contentType: 'application/json' },
  ])
  const panelExport = panel('Export to the binder')
  expect(panelExport).toHaveTextContent(exported.paper.content_hash)
  // The Binder's contract has no source for this module: the registration says so.
  expect(panelExport).toHaveTextContent('has no source for this module')
  expect(exported.binder_delivery.deliverable).toBe(false)
  // The paper and its exports are read again: the latest export now matches.
  expect(await within(panelExport).findByText('Current')).toBeInTheDocument()
  const table = within(panelExport).getByRole('table', { name: /^Registered working papers/ })
  expect(within(table).getByRole('row', { name: /^1 / })).toHaveTextContent('manager@firm')
  expect(within(table).getByRole('row', { name: /^1 / })).toHaveTextContent(
    registrations[0]?.content_hash ?? 'missing',
  )
  // The registration's hash is the paper's hash as it stood.
  expect(exported.paper.content_hash).toBe(ready.content_hash)
  expect(current.export.latest?.content_hash).toBe(ready.content_hash)
})

test('an export the backend refuses is shown in its words', async () => {
  await open(ready, [], {
    [exportPath(ready)]: refusal(refusals.noRun.status, refusals.noRun.body),
  })
  fireEvent.click(exportButton())
  const alert = await within(panel('Export to the binder')).findByRole('alert')
  expect(alert).toHaveTextContent('The paper was not exported')
  expect(alert).toHaveTextContent(refusals.noRun.body.detail)
  expect(alert).toHaveTextContent('answered 409')
  expect(posts()).toHaveLength(1)
})

test('after the engagement moves on the export is stale and a new run is needed first', async () => {
  await open(stale, registrations)
  const panelExport = panel('Export to the binder')
  expect(panelExport).toHaveTextContent('Latest export:Stale')
  expect(panelExport).toHaveTextContent('paper 1 on run 1')
  expect(exportButton()).toBeDisabled()
  expect(
    within(panelExport).getByRole('list', { name: 'Why the paper cannot be exported' }),
  ).toHaveTextContent('record a new run first')
  // The hash moved with the content.
  expect(stale.content_hash).not.toBe(current.content_hash)
})

test('nothing changed since the last export is refused, and the registration stands', async () => {
  await open(current, registrations, {
    [exportPath(current)]: refusal(refusals.unchanged.status, refusals.unchanged.body),
  })
  expect(panel('Export to the binder')).toHaveTextContent('Latest export:Current')
  fireEvent.click(exportButton())
  const alert = await within(panel('Export to the binder')).findByRole('alert')
  expect(alert).toHaveTextContent('nothing has changed since paper 1')
})

test('the export goes out once, however many times the button is pressed while it is processing', async () => {
  const answerLater = answered(201, exported)
  let release: (value: unknown) => void = () => undefined
  const pending = new Promise<unknown>((resolve) => {
    release = resolve
  })
  await open(ready, [], { [exportPath(ready)]: pending })
  fireEvent.click(exportButton())
  fireEvent.click(exportButton())
  expect(posts()).toHaveLength(1)
  expect(
    within(panel('Export to the binder')).getByRole('button', { name: 'Exporting…' }),
  ).toBeDisabled()
  release(answerLater)
  expect(await screen.findByText(/^Registered as paper 1/)).toBeInTheDocument()
  expect(posts()).toHaveLength(1)
})

